/// The column name std gives `param` of `feature`, if any.
pub fn column(feature: &str, param: &str) -> Option<&'static str> {
    COLUMNS.iter().find(|(f, p, _)| *f == feature && *p == param).map(|(_, _, c)| *c)
}
