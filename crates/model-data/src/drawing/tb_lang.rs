    /// The name in the Custom template's Language list.
    pub fn name(self) -> &'static str {
        match self {
            TitleLanguage::ChineseTraditional => "繁體中文",
            TitleLanguage::French => "Français",
            TitleLanguage::English => "English",
            TitleLanguage::German => "Deutsch",
            TitleLanguage::ChineseSimplified => "简体中文",
            TitleLanguage::Japanese => "日本語",
            TitleLanguage::Korean => "한국어",
            TitleLanguage::Spanish => "Español",
            TitleLanguage::Italian => "Italiano",
        }
    }

    pub fn is_english(self) -> bool {
        self == TitleLanguage::English
    }

    /// For `skip_serializing_if`.
    pub fn is_english_ref(&self) -> bool {
        self.is_english()
    }

    /// The "1 of 1" field of a new title block.
    pub fn sheet_field(self) -> String {
        self.strings().sheet_of.replace("{n}", "{sheet.number}").replace("{c}", "{sheet.count}")
    }

