//! Custom template › Language: the title block's labels in each of Onshape's
//! nine languages (live behaviours.md "Custom template › Language:
//! title-block texts per language", exact strings from Onshape's DXF
//! exports, including its own spellings). Values, zone labels and the
//! drawing UI are not localised.

use serde::{Deserialize, Serialize};

/// A title block language, in Onshape's list order.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum TitleLanguage {
    ChineseTraditional,
    French,
    #[default]
    English,
    German,
    ChineseSimplified,
    Japanese,
    Korean,
    Spanish,
    Italian,
}

/// The labels of the title block. `unless` holds `{u}` for the units word;
/// `sheet_of` holds `{n}` and `{c}`. A factor scales a label's text height
/// where Onshape shrinks the translation to fit its cell.
#[derive(Clone, Debug)]
pub struct TitleStrings {
    pub unless: &'static str,
    pub millimeters: &'static str,
    /// The inch word (None: not captured for this language; English is used).
    pub inches: Option<&'static str>,
    pub angular: &'static str,
    pub fractional: Option<&'static str>,
    pub surface_finish: &'static str,
    pub do_not_scale: &'static str,
    pub break_edges: &'static str,
    pub first_angle: &'static str,
    pub third_angle: Option<&'static str>,
    pub name: &'static str,
    pub signature: &'static str,
    pub date: &'static str,
    pub drawn: &'static str,
    pub checked: &'static str,
    pub approved: &'static str,
    pub material: &'static str,
    pub finish: &'static str,
    pub title: &'static str,
    pub size: &'static str,
    pub dwg_no: &'static str,
    pub rev: &'static str,
    pub scale: &'static str,
    pub weight: &'static str,
    pub sheet: &'static str,
    pub sheet_of: &'static str,
    /// Height factors: the units note, SURFACE FINISH, DO NOT SCALE
    /// DRAWING, DRAWN / CHECKED / APPROVED.
    pub unless_h: f64,
    pub surface_h: f64,
    pub dns_h: f64,
    pub signoff_h: f64,
}

