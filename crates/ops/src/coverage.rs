//! Coverage of the UI by the agent API: every UI command (the keyboard
//! shortcut registry, `crates/app/src/shortcuts.rs`, plus the Part Studio
//! feature registry, the assembly tool search and the edit descriptions)
//! with the operation that does the same, or why none is needed. The
//! coverage test (`tests/coverage.rs`) reads the app's sources and fails
//! when a UI command is missing here or an op named here doesn't exist.
//!
//! Part Studio feature shortcuts (`part_studio/shortcut_cmds.rs` FEATURES)
//! and every feature type are covered by `feature_add` automatically.

/// How a UI command is available to agents.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Cover {
    /// This operation (MCP tool name) does it.
    Op(&'static str),
    /// Not available yet (counted against coverage; the work list).
    Planned,
    /// UI-only: no model effect an agent needs (the reason).
    Ui(&'static str),
}

